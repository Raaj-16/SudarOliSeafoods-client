export function stockStatus(p) {
  if (p.stockQty <= 0) return 'out'
  if (p.stockQty <= 5) return 'low'
  return 'ok'
}

export function stockLabel(p) {
  const s = stockStatus(p)
  if (s === 'out') return 'Sold out'
  if (s === 'low') return `Only ${p.stockQty} left`
  return 'In stock'
}

export function minPrice(p) {
  return Math.min(...p.weights.map((w) => w.price))
}

